int usbd_msc_sector_read(uint8_t busid, uint8_t lun, uint64_t sector, uint8_t *buffer, uint32_t length)
{
    uint32_t i;

    if (sector == 0) {
        /* 保护性 MBR(PMBR) */
        memcpy(buffer, fake_pmbr, length);
    } else if (sector == 1) {
        /* 主 GPT 头(92B + 0) */
        memset(buffer, 0, length);
        memcpy(buffer, fake_gpt_head, 92);
    } else if ((sector >= 2) && (sector < 34)) {
        /* 分区表项数组:项1 = exFAT,其余 0 */
        memset(buffer, 0, length);
        if (sector == 2) {
            memcpy(buffer, fake_gpt_entries, 128);
        }
    } else if ((sector >= 0x9FFFFFFDFull) && (sector <= 0x9FFFFFFFEull)) {
        /* 备份分区表项数组(副本) */
        memset(buffer, 0, length);
        if (sector == 0x9FFFFFFDFull) {
            memcpy(buffer, fake_gpt_entries, 128);
        }
    } else if (sector == 0x9FFFFFFFFull) {
        /* 备份 GPT 头 */
        memset(buffer, 0, length);
        memcpy(buffer, fake_gpt_head_bak, 92);
    } else if ((sector >= FAKE_PART_LBA) && (sector < FAKE_PART_LBA + 24)) {
        /* exFAT 引导区 24 扇区（主 12 + 备份 12）：扇区 0/12 = BPB(512B 数组)，
         * 1-8/13-20 = 扩展签名 AA550000h，11/23 = 校验和扇区（0xCA0AED63×128），其余 0 */
        uint32_t ss = (uint32_t)((sector - FAKE_PART_LBA) % 12);
        if (ss == 0) {
            memcpy(buffer, fake_exfat_boot, length);
        } else if ((ss >= 1) && (ss <= 8)) {
            memset(buffer, 0, length);
            buffer[508] = 0x00; buffer[509] = 0x00; buffer[510] = 0x55; buffer[511] = 0xAA;
        } else if (ss == 11) {
            for (i = 0; i < length; i += 4) {
                buffer[i] = 0x0A; buffer[i+1] = 0xEE; buffer[i+2] = 0x13; buffer[i+3] = 0x4A;
            }
        } else {
            memset(buffer, 0, length);
        }
    } else if ((sector >= 2112) && (sector < 2112 + 81920)) {
        /* exFAT FAT 表:FAT[0]=F8, FAT[1]=FF, FAT[2]=3(位图链), FAT[3..5]=FF(EOF), 其余 0 */
        if (sector == 2112) {
            uint8_t fat_hdr[20] = {
                0xF8,0xFF,0xFF,0xFF, 0xFF,0xFF,0xFF,0xFF,
                0xFF,0xFF,0xFF,0xFF, 0xFF,0xFF,0xFF,0xFF,
                0xFF,0xFF,0xFF,0xFF
            };
            memcpy(buffer, fat_hdr, 20);
            memset(&buffer[20], 0, length - 20);
        } else {
            memset(buffer, 0, length);
        }
    } else if ((sector >= 88128) && (sector < 88128 + 8)) {
        /* 根目录（簇 4）：3 个目录项（96B）+ 0 */
        memset(buffer, 0, length);
        if (sector == 88128) {
            memcpy(buffer, fake_exfat_root, 96);
        }
    } else if ((sector >= 84032) && (sector < 84032 + 4096)) {
        /* 簇位图（簇 2-3，DataLength=1048568B=2 簇）：簇 2-5 已分配（首字节 0x3C） */
        memset(buffer, 0, length);
        if (sector == 84032) {
            buffer[0] = 0x1C;
        }
    } else if ((sector >= 92224) && (sector < 92224 + 12)) {
        /* Up-case 表（簇 5，压缩格式 60B） */
        memset(buffer, 0, length);
        if (sector == 92224) {
            memcpy(buffer, fake_exfat_upcase, 60);
        }
    } else {
        memset(buffer, 0, length); /* 数据全 0 */
    }
    return 0;
}

